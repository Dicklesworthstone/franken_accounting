//! Fair, launch-selected maintenance of native and functional period cells.
//!
//! One cycle advances at most one configured period/measure through the existing
//! facade. No second writer, journal interpretation, repair path or certified
//! checkpoint is introduced. An error remains attached to its period until
//! that period succeeds; it neither blocks other periods nor gets cleared by
//! an unrelated success. A cursor here is operational status, not evidence.

use core::fmt;
use std::collections::BTreeSet;

use asupersync::Cx;
use asupersync::fs::Vfs;
use fa::{AsyncBook, Book, Capability, Op, Profile};
use fa_cli::json::{Json, obj, s};
use fa_model::Id128;
use fgdb_types::context::PurposeContexts;

/// Scheduling/input bounds, not new accounting or durable-format limits.
pub const MAX_PERIODS: usize = 64;
pub const MAX_PERIOD_CODE_BYTES: usize = 128;
const MAX_ERROR_BYTES: usize = 1024;

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ConfigurationError(pub &'static str);

impl fmt::Display for ConfigurationError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.0)
    }
}

impl core::error::Error for ConfigurationError {}

/// The independent derived projection advanced by one scheduling attempt.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Measure {
    Native,
    Functional,
}

impl Measure {
    #[must_use]
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Native => "native",
            Self::Functional => "functional",
        }
    }
}

/// Explicit local selection; existing callers continue to maintain native cells.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum MeasureSelection {
    #[default]
    Native,
    Functional,
    Both,
}

impl MeasureSelection {
    pub fn parse(value: &str) -> Result<Self, ConfigurationError> {
        match value {
            "native" => Ok(Self::Native),
            "functional" => Ok(Self::Functional),
            "both" => Ok(Self::Both),
            _ => Err(ConfigurationError(
                "--register-measure must be native, functional, or both",
            )),
        }
    }

    #[must_use]
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Native => "native",
            Self::Functional => "functional",
            Self::Both => "both",
        }
    }

    const fn measures(self) -> &'static [Measure] {
        match self {
            Self::Native => &[Measure::Native],
            Self::Functional => &[Measure::Functional],
            Self::Both => &[Measure::Native, Measure::Functional],
        }
    }

    const fn scope(self) -> &'static str {
        match self {
            Self::Native => "native_posted_pending_period_cells",
            Self::Functional => "functional_posted_pending_period_cells",
            Self::Both => "native_and_functional_posted_pending_period_cells",
        }
    }
}

/// Validate without opening a book. Codes are exact: never trim, sort,
/// deduplicate, interpret as dates, or silently broaden them to a fiscal year.
pub fn validate_periods(periods: &[String]) -> Result<(), ConfigurationError> {
    if periods.is_empty() || periods.len() > MAX_PERIODS {
        return Err(ConfigurationError("require 1..=64 register periods"));
    }
    let mut seen = BTreeSet::new();
    for period in periods {
        if period.is_empty()
            || period.len() > MAX_PERIOD_CODE_BYTES
            || period.starts_with("--")
            || period.chars().any(|c| c.is_control() || c.is_whitespace())
        {
            return Err(ConfigurationError(
                "a register period must be an exact nonempty code of at most 128 bytes, without whitespace or a leading --",
            ));
        }
        if !seen.insert(period.as_str()) {
            return Err(ConfigurationError("register periods must be distinct"));
        }
    }
    Ok(())
}

/// Select the complete, fixed cohort generated by the book's fiscal calendar.
/// Periods need not exist yet: the selected maintainer reports their absence and
/// can advance them after creation without restarting or widening this cohort.
/// No stored period mirror or host calendar determines the selection.
pub fn fiscal_year_periods(
    calendar: &fa_time::FiscalCalendar,
    fiscal_year: i32,
) -> Result<Vec<String>, String> {
    let periods: Vec<_> = calendar
        .periods_for_year(fiscal_year)
        .map_err(|error| error.to_string())?
        .into_iter()
        .map(|period| period.code)
        .collect();
    validate_periods(&periods).map_err(|error| error.to_string())?;
    Ok(periods)
}

/// Only the operational metadata from a successful facade publication.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Publication {
    pub through: u64,
    pub published_at: u64,
    pub entries_decoded: usize,
    pub rebuilt: bool,
    pub wrote: bool,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct PeriodStatus {
    pub period: String,
    pub measure: Measure,
    pub attempts: u64,
    pub last_success: Option<Publication>,
    pub error: Option<String>,
}

/// Narrow adapter: production and virtual-time tests call the same selected
/// facade maintainer, including its atomic cursor and retained-tail rules.
pub(crate) trait RegisterBook {
    fn book_id(&self) -> Id128;
    async fn advance(
        &mut self,
        cx: &Cx,
        capability: &Capability,
        period: &str,
        measure: Measure,
    ) -> Result<Publication, String>;
}

impl RegisterBook for Book {
    fn book_id(&self) -> Id128 {
        self.context().book_id
    }

    async fn advance(
        &mut self,
        cx: &Cx,
        capability: &Capability,
        period: &str,
        measure: Measure,
    ) -> Result<Publication, String> {
        match measure {
            Measure::Native => {
                let result =
                    Book::advance_registers_with(self, cx, capability.holder(), capability, period)
                        .await
                        .map_err(|e| e.to_string())?
                        .map_err(|refusal| refusal.to_string())?;
                Ok(Publication {
                    through: result.through.0,
                    published_at: result.published_at.0,
                    entries_decoded: result.entries_decoded,
                    rebuilt: result.rebuilt,
                    wrote: result.wrote,
                })
            }
            Measure::Functional => {
                let result = Book::advance_functional_registers_with(
                    self,
                    cx,
                    capability.holder(),
                    capability,
                    period,
                )
                .await
                .map_err(|e| e.to_string())?
                .map_err(|refusal| refusal.to_string())?;
                Ok(Publication {
                    through: result.through.0,
                    published_at: result.published_at.0,
                    entries_decoded: result.entries_decoded,
                    rebuilt: result.rebuilt,
                    wrote: result.wrote,
                })
            }
        }
    }
}

impl<V: Vfs + Clone, B: Vfs + Clone> RegisterBook for AsyncBook<V, B> {
    fn book_id(&self) -> Id128 {
        self.context().book_id
    }

    async fn advance(
        &mut self,
        cx: &Cx,
        capability: &Capability,
        period: &str,
        measure: Measure,
    ) -> Result<Publication, String> {
        let purposes = PurposeContexts::narrow_runtime_root(cx);
        match measure {
            Measure::Native => {
                let result = AsyncBook::advance_registers(
                    self,
                    &purposes,
                    capability.holder(),
                    capability,
                    period,
                )
                .await
                .map_err(|e| e.to_string())?
                .map_err(|refusal| refusal.to_string())?;
                Ok(Publication {
                    through: result.through.0,
                    published_at: result.published_at.0,
                    entries_decoded: result.entries_decoded,
                    rebuilt: result.rebuilt,
                    wrote: result.wrote,
                })
            }
            Measure::Functional => {
                let result = AsyncBook::advance_functional_registers(
                    self,
                    &purposes,
                    capability.holder(),
                    capability,
                    period,
                )
                .await
                .map_err(|e| e.to_string())?
                .map_err(|refusal| refusal.to_string())?;
                Ok(Publication {
                    through: result.through.0,
                    published_at: result.published_at.0,
                    entries_decoded: result.entries_decoded,
                    rebuilt: result.rebuilt,
                    wrote: result.wrote,
                })
            }
        }
    }
}

/// Owned by TimedWork, hence by the same serving region as the book writer.
/// Recreating this scheduler after restart never invents a consumed frontier:
/// each maintainer reloads its atomically persisted state on each call.
#[derive(Debug)]
pub struct RegisterWork {
    measures: MeasureSelection,
    periods: Vec<PeriodStatus>,
    next: usize,
    attempts: u64,
    // Explicit local maintenance configuration owns this service authority.
    // Bind it once to the first book, retaining any construction refusal;
    // another book never causes a fresh implicit grant. This authorizes no
    // clock observation, posting, expiry or reversal work and is never a
    // capability presented by, or returned to, a wire/MCP caller.
    authority: Option<Result<Capability, String>>,
}

impl RegisterWork {
    pub fn new(periods: Vec<String>) -> Result<Self, ConfigurationError> {
        Self::for_measures(periods, MeasureSelection::Native)
    }

    /// Rotate over the complete period/measure product, so a busy or failed
    /// functional projection cannot starve native cells or another period.
    pub fn for_measures(
        periods: Vec<String>,
        measures: MeasureSelection,
    ) -> Result<Self, ConfigurationError> {
        validate_periods(&periods)?;
        Ok(Self {
            measures,
            periods: periods
                .into_iter()
                .flat_map(|period| {
                    measures
                        .measures()
                        .iter()
                        .map(move |&measure| PeriodStatus {
                            period: period.clone(),
                            measure,
                            attempts: 0,
                            last_success: None,
                            error: None,
                        })
                })
                .collect(),
            next: 0,
            attempts: 0,
            authority: None,
        })
    }

    #[must_use]
    pub fn periods(&self) -> &[PeriodStatus] {
        &self.periods
    }

    #[must_use]
    pub fn attempts(&self) -> u64 {
        self.attempts
    }

    /// Cancellation before admission performs no call and does not advance
    /// the rotation. Failures are recorded, not retried in a tight drain loop.
    /// This bounds publication attempts, not the selected fold's CPU/I/O cost.
    pub(crate) async fn run_cycle<B: RegisterBook>(&mut self, cx: &Cx, book: &mut B) {
        if cx.checkpoint().is_err() {
            return;
        }
        let index = self.next;
        self.next = (index + 1) % self.periods.len();
        self.attempts = self.attempts.saturating_add(1);
        let authority = self.authority.get_or_insert_with(|| {
            let book_id = book.book_id();
            let system = fa_journal::rows::system_principal(book_id);
            Capability::new(
                system,
                Profile::System,
                &[Op::Read, Op::Verify, Op::Maintain],
                system,
            )
            .and_then(|capability| capability.for_books(&[book_id]))
            .map_err(|error| error.to_string())
        });
        let status = &mut self.periods[index];
        status.attempts = status.attempts.saturating_add(1);
        let result = match authority {
            Ok(capability) => {
                book.advance(cx, capability, &status.period, status.measure)
                    .await
            }
            Err(error) => Err(error.clone()),
        };
        match result {
            Ok(publication) => {
                status.last_success = Some(publication);
                status.error = None;
            }
            Err(error) => {
                // Bound status independently of any upstream diagnostic.
                // Truncate only at a UTF-8 boundary; preserve earlier success
                // as historical status, never relabel it as current success.
                let mut end = error.len().min(MAX_ERROR_BYTES);
                while !error.is_char_boundary(end) {
                    end -= 1;
                }
                let truncated = end < error.len();
                let mut error = error[..end].to_owned();
                if truncated {
                    error.push_str(" [truncated]");
                }
                status.error = Some(error);
            }
        }
    }

    #[must_use]
    pub fn status(&self) -> Json {
        let seq = |value: Option<u64>| value.map_or(Json::Null, |n| Json::Int(i128::from(n)));
        obj(vec![
            ("enabled", Json::Bool(true)),
            ("scope", s(self.measures.scope())),
            ("measure", s(self.measures.as_str())),
            ("periods_per_cycle", Json::Int(1)),
            ("attempts", Json::Int(i128::from(self.attempts))),
            ("next_period", s(&self.periods[self.next].period)),
            ("next_measure", s(self.periods[self.next].measure.as_str())),
            ("certified", Json::Bool(false)),
            (
                "periods",
                Json::Arr(
                    self.periods
                        .iter()
                        .map(|status| {
                            let last = status.last_success.as_ref();
                            obj(vec![
                                ("period", s(&status.period)),
                                ("measure", s(status.measure.as_str())),
                                ("attempts", Json::Int(i128::from(status.attempts))),
                                ("through", seq(last.map(|p| p.through))),
                                (
                                    "published_at",
                                    seq(last.filter(|p| p.wrote).map(|p| p.published_at)),
                                ),
                                (
                                    "entries_decoded",
                                    last.map_or(Json::Null, |p| {
                                        Json::Int(p.entries_decoded as i128)
                                    }),
                                ),
                                (
                                    "rebuilt",
                                    last.map_or(Json::Null, |p| Json::Bool(p.rebuilt)),
                                ),
                                ("wrote", last.map_or(Json::Null, |p| Json::Bool(p.wrote))),
                                ("error", status.error.as_ref().map_or(Json::Null, s)),
                            ])
                        })
                        .collect(),
                ),
            ),
        ])
    }

    #[must_use]
    pub fn status_text(&self) -> String {
        let failures = self
            .periods
            .iter()
            .filter(|period| period.error.is_some())
            .count();
        format!(
            "register maintenance: {} configured period/measure tasks, one attempt per cycle, {} attempts, {} task errors; next {} ({}); derived caches only, not certified checkpoints",
            self.periods.len(),
            self.attempts,
            failures,
            self.periods[self.next].period,
            self.periods[self.next].measure.as_str(),
        )
    }
}


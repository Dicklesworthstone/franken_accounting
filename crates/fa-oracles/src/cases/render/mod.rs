//! The case README renderer (docs/FORENSIC_CASE_STUDIES_PLAN.md §12.3; bead
//! fa-yugf.31, A14): a pure function of a loaded case and its last green
//! run's records, so the same inputs give the same bytes and the committed
//! README cannot drift from the evidence.
//!
//! Every claim sentence comes from its expectation's template
//! ([`templates::TEXTS`]); there is no free-text path. Sentences carry their
//! sources' assertion phrases from [`Expectation::phrases`] unchanged, a D
//! its procedure's claim class and calibration clause, and a P the
//! documented attribute it varies. A row the run did not evaluate renders
//! only as "not yet evaluated: <reason>", never with an outcome; a P cell
//! the record does not support is marked *unconstrained*. Only run-invariant
//! fields render, and [`lint`] refuses the wording §0.3 forbids. The
//! program overview, the Limits section and transcript mode are A14b's and
//! OD 4's.

pub mod lint;
pub mod templates;


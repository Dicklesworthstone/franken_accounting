/// The generated-file header every README starts with.
pub const GENERATED: &str = "<!-- GENERATED by fa-oracles cases::render (A14) from this case's data files and its last green run. Never edit by hand: `FA_CASES_RENDER=print cargo test -p fa-cli --test cases rendered_docs_do_not_drift -- --nocapture` prints the current text. -->";

/// A run's records, as A7a's runner keeps them.
#[derive(Clone, Copy, Debug)]
pub struct RunRecords<'a> {
    pub steps: &'a [StepRecord],
    pub verdicts: &'a [VerdictRecord],
    /// No row FAILed and every claimed expectation PASSed (the runner's
    /// `rows_ok`).
    pub green: bool,
}

/// Why a README was not rendered.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum RenderError {
    /// The run was not green: a README renders only from a green run.
    NotGreen,
    /// A template that does not fill.
    Template { expectation: String, why: String },
    /// The rendered text breaks the wording or run-invariance lint.
    Lint(Vec<String>),
}

/// The README of `case` from its run's records.
///
/// # Errors
///
/// [`RenderError`]: a run that is not green, a template that does not fill,
/// or a lint problem in the rendered text.
pub fn render_readme(case: &Case, run: &RunRecords<'_>) -> Result<String, RenderError> {
    if !run.green {
        return Err(RenderError::NotGreen);
    }
    let rows = rows_by_expectation(run.verdicts);
    let mut out = String::new();
    header(case, &mut out);
    record(case, &mut out);
    books(case, &rows, &mut out);
    results(case, &rows, &mut out)?;
    runner_rows(case, &rows, &mut out);
    not_yet(case, &rows, &mut out);
    let mut problems = lint::problems(&out);
    // §2.8: real people appear only as role labels. A failure names the
    // hash, never the token.
    problems.extend(
        names::denied(&out, deny(case))
            .into_iter()
            .map(|h| format!("deny-listed name token {h}")),
    );
    if problems.is_empty() {
        Ok(out)
    } else {
        Err(RenderError::Lint(problems))
    }
}

fn deny(case: &Case) -> &[String] {
    case.roles.deny_hashes.as_deref().unwrap_or(&[])
}

/// A source's title as the README shows it. A title carrying a deny-listed
/// name token (an SEC complaint's caption names the people it sues) is
/// withheld whole: the deny list holds surnames but not every given name,
/// so a partial redaction would still identify (§2.8: minimize names). The
/// publisher column still says who issued it.
fn title_shown(title: &str, deny: &[String]) -> String {
    if names::denied(title, deny).is_empty() {
        title.to_string()
    } else {
        "title withheld: it names a person (plan §2.8)".to_string()
    }
}

/// `amount` (as [`format_amount`] writes it) with its whole part grouped by
/// thousands: presentation only, never arithmetic.
fn grouped(amount: &str) -> String {
    let (sign, rest) = amount.strip_prefix('-').map_or(("", amount), |r| ("-", r));
    let (whole, frac) = rest
        .split_once('.')
        .map_or((rest, None), |(w, f)| (w, Some(f)));
    let mut g = String::new();
    for (i, c) in whole.chars().enumerate() {
        if i > 0 && (whole.len() - i) % 3 == 0 {
            g.push(',');
        }
        g.push(c);
    }
    match frac {
        Some(f) => format!("{sign}{g}.{f}"),
        None => format!("{sign}{g}"),
    }
}

/// The verdict records of each expectation id, in run order.
fn rows_by_expectation(verdicts: &[VerdictRecord]) -> BTreeMap<&str, Vec<&VerdictRecord>> {
    let mut out: BTreeMap<&str, Vec<&VerdictRecord>> = BTreeMap::new();
    for v in verdicts {
        out.entry(v.expectation.as_str()).or_default().push(v);
    }
    out
}

/// An expectation's verdict: the worst of its rows; UNRUN with none.
fn verdict_of(rows: &BTreeMap<&str, Vec<&VerdictRecord>>, id: &str) -> RowVerdict {
    rows.get(id).map_or(RowVerdict::Unrun, |rs| {
        RowVerdict::worst(rs.iter().map(|r| r.verdict))
    })
}

/// A Markdown table cell: pipes escaped, line breaks flattened.
fn cell(s: &str) -> String {
    s.replace('|', "\\|").replace('\n', " ")
}

fn ids(list: &[String]) -> String {
    if list.is_empty() {
        return "-".to_string();
    }
    list.iter()
        .map(|i| format!("`{i}`"))
        .collect::<Vec<_>>()
        .join(", ")
}

fn header(case: &Case, out: &mut String) {
    let h = &case.header;
    let _ = writeln!(out, "{GENERATED}\n");
    let _ = writeln!(out, "# {}\n", h.title);
    let letter = h.letter.as_deref().unwrap_or("-");
    let _ = writeln!(
        out,
        "Case `{}` (letter {letter}), version {}. Scope: {}.\n",
        h.id, h.version, h.scope
    );
    let _ = writeln!(
        out,
        "Claimed rows: {}. A claimed row that stops passing fails the case, so every claimed row below passed in the run this document was rendered from.\n",
        ids(&h.claims)
    );
}

/// The registered scale of a unit, if any.
fn scale_of(unit: &str) -> Option<u8> {
    fa_registry::units_embedded()
        .ok()?
        .into_iter()
        .find(|u| u.code == unit)
        .map(|u| u.scale)
}

/// A fact's values as written in the book: an amount at its unit's scale.
fn values_of(case: &Case, fact: &str) -> String {
    let mut vs: Vec<_> = case.values.iter().filter(|v| v.fact == fact).collect();
    vs.sort_by_key(|v| v.ordinal);
    if vs.is_empty() {
        return "-".to_string();
    }
    vs.iter()
        .map(|v| {
            match (
                v.unit.is_empty(),
                scale_of(&v.unit),
                v.value.parse::<i128>(),
            ) {
                (false, Some(scale), Ok(minor)) => {
                    format!("{} {}", grouped(&format_amount(minor, scale)), v.unit)
                }
                _ => v.value.clone(),
            }
        })
        .collect::<Vec<_>>()
        .join("; ")
}

fn record(case: &Case, out: &mut String) {
    let _ = writeln!(out, "## What the record says\n");
    let _ = writeln!(out, "### Sources\n");
    let _ = writeln!(
        out,
        "| Source | Title | Publisher | Status | Filed | Retrieved |"
    );
    let _ = writeln!(out, "|---|---|---|---|---|---|");
    for s in &case.sources {
        let phrase = source_phrase(s, s.assertion_status, &phrase_table).unwrap_or("-");
        let _ = writeln!(
            out,
            "| `{}` | {} | {} | {phrase} | {} | {} |",
            s.id,
            cell(&title_shown(&s.title, deny(case))),
            cell(&s.publisher),
            s.filed_on
                .as_deref()
                .filter(|d| !d.is_empty())
                .unwrap_or("-"),
            s.retrieval_route.as_str()
        );
    }
    let _ = writeln!(out, "\n### Sourced facts\n");
    let _ = writeln!(
        out,
        "Each fact is bound by its anchor and the SHA-256 of its quote, re-verified offline (receipts.toml).\n"
    );
    let _ = writeln!(
        out,
        "| Fact | Source | Anchor | Value | Status | Granularity |"
    );
    let _ = writeln!(out, "|---|---|---|---|---|---|");
    for f in &case.facts {
        let Some(s) = f.sourced() else { continue };
        let status = case
            .sources
            .iter()
            .find(|x| x.id == s.source)
            .and_then(|src| {
                let status = s
                    .assurance
                    .and_then(assurance_status)
                    .unwrap_or(src.assertion_status);
                source_phrase(src, status, &phrase_table)
            })
            .unwrap_or("-");
        let _ = writeln!(
            out,
            "| `{}` | `{}` | `{}` | {} | {status} | {} |",
            f.id,
            s.source,
            cell(&s.anchor),
            cell(&values_of(case, &f.id)),
            s.granularity.as_str()
        );
    }
    let readings: Vec<_> = case
        .facts
        .iter()
        .filter(|f| !matches!(f.provenance, Provenance::Sourced(_)))
        .collect();
    if readings.is_empty() {
        let _ = writeln!(out);
        return;
    }
    let _ = writeln!(out, "\n### Readings of the record\n");
    for f in readings {
        match &f.provenance {
            Provenance::Interpretation(i) => {
                let _ = writeln!(
                    out,
                    "- `{}`, an interpretation of {}, read by `{}` and second reader `{}`: {}",
                    f.id,
                    ids(&i.from),
                    i.reader,
                    i.second_reader,
                    cell(&i.rationale)
                );
            }
            Provenance::Derived(d) => {
                let _ = writeln!(
                    out,
                    "- `{}`, derived by `{}` from {}: {}",
                    f.id,
                    d.rule,
                    ids(&d.from),
                    cell(&values_of(case, &f.id))
                );
            }
            Provenance::Synthetic(s) => {
                let _ = writeln!(
                    out,
                    "- `{}`, synthetic ({}): {}",
                    f.id,
                    cell(&s.discipline),
                    cell(&s.reason)
                );
            }
            Provenance::Sourced(_) => {}
        }
    }
    let _ = writeln!(out);
}

fn self_row(case: &Case, rows: &BTreeMap<&str, Vec<&VerdictRecord>>, book: &BookVariant) -> String {
    let letter = case.header.letter.as_deref().unwrap_or(&case.header.id);
    let id = format!("{letter}-SELF-{}", book.stem);
    match rows.get(id.as_str()).and_then(|rs| rs.first()) {
        Some(r) if r.verdict == RowVerdict::Pass => "franken_accounting's own `jet.self_sourced_evidence` reports that every posting here rests on documents this reconstruction uploaded itself.".to_string(),
        Some(r) => format!(
            "franken_accounting's own `jet.self_sourced_evidence` self-disclosure (`{id}`): not yet evaluated: {}.",
            r.reason.as_deref().unwrap_or("-")
        ),
        None => format!("The self-disclosure row `{id}` did not run."),
    }
}

fn books(case: &Case, rows: &BTreeMap<&str, Vec<&VerdictRecord>>, out: &mut String) {
    let _ = writeln!(out, "## How this book was built\n");
    for variant in &case.header.variants {
        let Some(book) = case.books.get(variant) else {
            continue;
        };
        let _ = writeln!(out, "### Book `{}` ({})\n", book.stem, book.kind.as_str());
        let _ = writeln!(out, "{}\n", self_row(case, rows, book));
        let _ = writeln!(
            out,
            "Opened {} in {}, on the `{}` calendar.\n",
            book.book.opening_date, book.book.base_unit, book.book.calendar
        );
        let _ = writeln!(out, "| Period | Start | End | Fiscal year | Kind |");
        let _ = writeln!(out, "|---|---|---|---|---|");
        for p in &book.periods {
            let _ = writeln!(
                out,
                "| `{}` | {} | {} | {} | {} |",
                p.code, p.start, p.end, p.fiscal_year, p.kind
            );
        }
        let _ = writeln!(out, "\n| Account | Type | Named by |");
        let _ = writeln!(out, "|---|---|---|");
        for a in &book.accounts {
            let _ = writeln!(
                out,
                "| `{}` | {} | `{}` |",
                a.code, a.account_type, a.name_fact
            );
        }
        let _ = writeln!(out, "\n| Intent | Fact | Class | Effective |");
        let _ = writeln!(out, "|---|---|---|---|");
        for i in &book.intents {
            let _ = writeln!(
                out,
                "| `{}` | `{}` | {} | {} |",
                i.id, i.fact, i.class, i.effective_date
            );
        }
        if !book.documents.is_empty() {
            let _ = writeln!(out, "\n| Document | Stands for | Grade |");
            let _ = writeln!(out, "|---|---|---|");
            for d in &book.documents {
                let _ = writeln!(out, "| `{}` | `{}` | {} |", d.id, d.stub_of, d.grade);
            }
        }
        if !book.defaults.is_empty() {
            let _ = writeln!(
                out,
                "\nDeclared defaults (each an encoding choice the record does not fix):\n"
            );
            let _ = writeln!(out, "| Attribute | Rule | Why |");
            let _ = writeln!(out, "|---|---|---|");
            for d in &book.defaults {
                let _ = writeln!(
                    out,
                    "| `{}` | `{}` | {} |",
                    d.attribute,
                    d.rule,
                    cell(&d.rationale)
                );
            }
        }
        let _ = writeln!(out);
    }
}

/// The template slots of an expectation. Its inputs are its basis facts
/// other than the values it publishes (a T's B is compared, never an input).
fn slot_values(case: &Case, e: &Expectation) -> Vec<(&'static str, String)> {
    let f = &e.fields;
    let s = |k: &str| f.str(k).unwrap_or("-").to_string();
    let changed = match (f.str("changed_attribute"), f.str("changed_value")) {
        (Some(a), Some(v)) => format!("`{a}` were `{v}`"),
        _ => "-".to_string(),
    };
    let published = e.published_facts(case);
    let inputs: Vec<String> = f
        .strs("basis")
        .unwrap_or(&[])
        .iter()
        .filter(|b| !published.contains(&b.as_str()))
        .cloned()
        .collect();
    vec![
        ("id", e.id.clone()),
        ("variant", s("book_variant")),
        ("inputs", ids(&inputs)),
        ("procedure", s("procedure")),
        (
            "version",
            f.int("version")
                .map_or_else(|| "-".into(), |v| v.to_string()),
        ),
        ("kind", s("kind")),
        ("refusal", s("refusal")),
        ("attribute", s("attribute")),
        ("law_row", s("law_row")),
        ("mechanism", format!("`{}`", s("mechanism"))),
        ("parent", format!("`{}`", s("parent"))),
        ("changed", changed),
        ("expect", s("expect")),
        ("rule", s("rule")),
    ]
}

fn type_name(kind: ExpectationType) -> &'static str {
    match kind {
        ExpectationType::D => "detection",
        ExpectationType::P => "first refusal at commit",
        ExpectationType::T => "exact tie-out",
        ExpectationType::C => "consistency check",
        ExpectationType::R => "read-back",
        ExpectationType::N => "negative result",
        ExpectationType::Cf => "counterfactual",
    }
}

/// The observed tokens of a row, as the run projected them.
fn observed(r: &VerdictRecord) -> String {
    if r.verdict != RowVerdict::Pass {
        return format!("not yet evaluated: {}", r.reason.as_deref().unwrap_or("-"));
    }
    r.projection
        .iter()
        .map(|(k, v)| format!("{k}={v}"))
        .collect::<Vec<_>>()
        .join(" ")
}

fn row_table(e: &Expectation, rs: &[&VerdictRecord], out: &mut String) {
    let _ = writeln!(
        out,
        "| Target | Cell | Read as | Verdict | Record | Observed |"
    );
    let _ = writeln!(out, "|---|---|---|---|---|---|");
    for r in rs {
        let record = if r
            .projection
            .iter()
            .any(|(k, v)| k == "record_consistent" && v == "false")
        {
            "unconstrained"
        } else {
            "record-consistent"
        };
        let read_as = if r.kind == e.kind.as_str() {
            r.kind.clone()
        } else {
            format!("{} (re-typed from {})", r.kind, e.kind.as_str())
        };
        let _ = writeln!(
            out,
            "| `{}` | `{}` | {read_as} | {} | {record} | {} |",
            r.target.as_deref().unwrap_or("-"),
            cell(&r.cell),
            r.verdict.as_str(),
            cell(&observed(r))
        );
    }
}

fn results(
    case: &Case,
    rows: &BTreeMap<&str, Vec<&VerdictRecord>>,
    out: &mut String,
) -> Result<(), RenderError> {
    let Some(set) = &case.expectations else {
        return Ok(());
    };
    let procedures = Procedures::embedded().ok();
    let _ = writeln!(out, "## Findings, refusals, tie-outs and read-backs\n");
    for e in &set.expectations {
        let template = e.fields.str("statement_template").unwrap_or("-");
        let verdict = verdict_of(rows, &e.id);
        let _ = writeln!(out, "### `{}`: {} ({template})\n", e.id, type_name(e.kind));
        if verdict == RowVerdict::Pass {
            let text = templates::text(template).ok_or_else(|| RenderError::Template {
                expectation: e.id.clone(),
                why: format!("no text for template `{template}`"),
            })?;
            let sentence = templates::fill(text, &slot_values(case, e)).map_err(|why| {
                RenderError::Template {
                    expectation: e.id.clone(),
                    why,
                }
            })?;
            let _ = writeln!(out, "{sentence}\n");
        } else {
            let mut reasons: Vec<&str> = rows
                .get(e.id.as_str())
                .into_iter()
                .flatten()
                .filter_map(|r| r.reason.as_deref())
                .collect();
            reasons.sort_unstable();
            reasons.dedup();
            let _ = writeln!(
                out,
                "Not yet evaluated: {}. No outcome is stated for this row.\n",
                if reasons.is_empty() {
                    "the run did not reach it".to_string()
                } else {
                    reasons.join("; ")
                }
            );
        }
        let phrases = e.phrases(case);
        if !phrases.is_empty() {
            let list = phrases
                .iter()
                .map(|(s, p)| format!("`{s}` ({p})"))
                .collect::<Vec<_>>()
                .join(", ");
            let _ = writeln!(out, "Sources: {list}.\n");
        }
        if e.kind == ExpectationType::D
            && let (Some(id), Some(version)) = (e.fields.str("procedure"), e.fields.int("version"))
            && let Some(p) = procedures
                .as_ref()
                .and_then(|ps| ps.get(id))
                .filter(|p| i128::from(p.version) == version)
        {
            let _ = writeln!(
                out,
                "Claim class: {}. Calibration: {}.\n",
                p.claim.name(),
                calibration_clause(p.calibration)
            );
        }
        if let Some(rs) = rows.get(e.id.as_str()) {
            row_table(e, rs, out);
            let _ = writeln!(out);
        }
    }
    for n in &set.notes {
        let basis = ids(n.fields.strs("basis").unwrap_or(&[]));
        let text = templates::text("NOTE.observation").unwrap_or("-");
        let sentence =
            templates::fill(text, &[("inputs", basis)]).map_err(|why| RenderError::Template {
                expectation: n.id.clone(),
                why,
            })?;
        let _ = writeln!(
            out,
            "### `{}`: note (NOTE.observation)\n\n{sentence}\n",
            n.id
        );
    }
    Ok(())
}

/// The runner-generated restatement case rows (`<letter>-CASE-<case id>`).
fn runner_rows(case: &Case, rows: &BTreeMap<&str, Vec<&VerdictRecord>>, out: &mut String) {
    let letter = case.header.letter.as_deref().unwrap_or(&case.header.id);
    let prefix = format!("{letter}-CASE-");
    let cases: Vec<(&str, &Vec<&VerdictRecord>)> = rows
        .iter()
        .filter(|(id, _)| id.starts_with(&prefix))
        .map(|(id, rs)| (*id, rs))
        .collect();
    if cases.is_empty() {
        return;
    }
    let _ = writeln!(out, "## Restatement cases\n");
    let _ = writeln!(
        out,
        "The runner reads each restatement case back with `fa case show` after its history: its state, its kind and its determination day.\n"
    );
    let _ = writeln!(out, "| Row | Book | Verdict | Observed |");
    let _ = writeln!(out, "|---|---|---|---|");
    for (id, rs) in cases {
        for r in rs {
            let _ = writeln!(
                out,
                "| `{id}` | `{}` | {} | {} |",
                r.book_variant,
                r.verdict.as_str(),
                cell(&observed(r))
            );
        }
    }
    let _ = writeln!(out);
}

fn not_yet(case: &Case, rows: &BTreeMap<&str, Vec<&VerdictRecord>>, out: &mut String) {
    let Some(set) = &case.expectations else {
        return;
    };
    let pending: Vec<&Expectation> = set
        .expectations
        .iter()
        .filter(|e| verdict_of(rows, &e.id) != RowVerdict::Pass)
        .collect();
    if pending.is_empty() {
        return;
    }
    let _ = writeln!(out, "## Not yet evaluated\n");
    let _ = writeln!(
        out,
        "These rows are not claimed: the run did not evaluate them to a verdict, so this document states no outcome for them.\n"
    );
    for e in pending {
        let mut reasons: Vec<&str> = rows
            .get(e.id.as_str())
            .into_iter()
            .flatten()
            .filter_map(|r| r.reason.as_deref())
            .collect();
        reasons.sort_unstable();
        reasons.dedup();
        let _ = writeln!(
            out,
            "- `{}`: {}",
            e.id,
            if reasons.is_empty() {
                "the run did not reach it".to_string()
            } else {
                reasons.join("; ")
            }
        );
    }
    let _ = writeln!(out);
}

